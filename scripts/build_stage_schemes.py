        for i, (t, k, gap) in enumerate(steps):
            w = int(len(t) * 7.6 + 26)
            aw = max(46, int(len(gap) * 6.6 + 16)) if i else 0
            if x + aw + w > W - 10:
                x = lx; line_y += 52
            if i:
                row.append(arrow_right(x + 2, x + aw - 2, line_y + 17, '#9aa3bb', dash=False))
