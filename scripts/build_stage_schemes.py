def esc(s):
    return html.escape(s, quote=True)


def wrap(text, limit):
    words, lines, cur = text.split(), [], ''
    for w in words:
        if cur and len(cur) + 1 + len(w) > limit:
            lines.append(cur); cur = w
        else:
            cur = (cur + ' ' + w).strip()
    if cur:
        lines.append(cur)
    return lines


def box(x, y, w, n, chars):
    """блок этапа; возвращает (svg, высота)"""
    color = KIND[n['kind']][0]
    lane_w = len(n['lane']) * 6.6 + 30 if n['lane'] else 0
    tl = wrap(n['title'], int((w - 30 - lane_w) / 8.8))  # жирный 15px ≈ 8.8px на букву
    dl = wrap(n['desc'], int((w - 30) / 7.1)) if n['desc'] else []  # 13px ≈ 7.1px
    h = 16 + len(tl) * 18 + (6 if dl else 0) + len(dl) * 17 + 12
    out = ['<rect x="%d" y="%d" width="%d" height="%d" rx="10" fill="#fff" stroke="#d5dbe8"/>' % (x, y, w, h),
           '<rect x="%d" y="%d" width="6" height="%d" rx="3" fill="%s"/>' % (x, y, h, color)]
    if n['lane']:
        lw = len(n['lane']) * 6.6 + 14
        out.append('<rect x="%d" y="%d" width="%d" height="18" rx="9" fill="%s" opacity="0.13"/>' % (x + w - lw - 8, y + 8, lw, color))
        out.append('<text x="%d" y="%d" font-size="11" font-weight="bold" fill="%s" text-anchor="middle">%s</text>' % (
            x + w - lw / 2 - 8, y + 21, color, esc(n['lane'])))
    yy = y + 16
    for i, t in enumerate(tl):
        yy += 18
        out.append('<text x="%d" y="%d" font-size="15" font-weight="bold" fill="#14182e">%s</text>' % (x + 18, yy - 4, esc(t)))
    yy += 6 if dl else 0
    for t in dl:
        yy += 17
        out.append('<text x="%d" y="%d" font-size="13" fill="#3a4257">%s</text>' % (x + 18, yy - 4, esc(t)))
    return ''.join(out), h


def gap_label(x, y, text, color='#d9480f', anchor='start'):
    return '<text x="%d" y="%d" font-size="12.5" font-weight="bold" fill="%s" text-anchor="%s">%s</text>' % (x, y, color, anchor, esc(text))


def arrow_down(x, y1, y2, color='#9aa3bb', dash=False):
    d = ' stroke-dasharray="5 4"' if dash else ''
    return ('<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="2"%s/>'
            '<polygon points="%d,%d %d,%d %d,%d" fill="%s"/>') % (x, y1, x, y2 - 7, color, d, x - 6, y2 - 8, x + 6, y2 - 8, x, y2, color)


def arrow_right(x1, x2, y, color, dash=True):
    d = ' stroke-dasharray="5 4"' if dash else ''
    return ('<line x1="%d" y1="%d" x2="%d" y2="%d" stroke="%s" stroke-width="2"%s/>'
            '<polygon points="%d,%d %d,%d %d,%d" fill="%s"/>') % (x1, y, x2 - 7, y, color, d, x2 - 8, y - 6, x2 - 8, y + 6, x2, y, color)


