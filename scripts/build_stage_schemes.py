def scheme_svg(s):
    parts = []
    # заголовки столбцов
    parts.append('<text x="%d" y="18" font-size="12" font-weight="bold" fill="#5c6478">АКТИВНАЯ ВЕТКА · делает каждый шаг</text>' % MX)
    if any(n.get('side') for n in s['main']):
        parts.append('<text x="%d" y="18" font-size="12" font-weight="bold" fill="#e03131">ЕСЛИ НЕ СДЕЛАЛ ШАГ</text>' % SX)
    if s.get('lazy'):
        parts.append('<text x="%d" y="18" font-size="12" font-weight="bold" fill="#5c6478">ЛЕНИВАЯ ВЕТКА · только «Старт»</text>' % LX)
    y = 34
    ys = []
    for i, n in enumerate(s['main']):
        if i:
            parts.append(arrow_down(MX + 40, y - 46, y))
            if n['gap']:
                parts.append(gap_label(MX + 52, y - 19, n['gap']))
        svg, h = box(MX, y, MW, n, MC)
        parts.append(svg)
        ys.append(y)
        hs = h
        if n.get('side'):
            label, text = n['side']
            sn = N('push', '', label, text)
            ssvg, sh = box(SX, y, SW, sn, SC)
            parts.append(arrow_right(MX + MW, SX, y + 26, '#e03131'))
            parts.append(ssvg)
            hs = max(h, sh)
        y += hs + 46
    bottom = y - 46
    if s.get('lazy'):
        ly = ys[s.get('lazy_from', 0)]  # у этого узла нет бокового дожима — стрелка идёт поверх пустого столбца
        mid = (MX + MW + LX) // 2
        parts.append(arrow_right(MX + MW, LX, ly + 26, '#868e96'))
        parts.append(gap_label(mid, ly + 18, s.get('lazy_label', ''), '#5c6478', 'middle'))
        for j, n in enumerate(s['lazy']):
            if j:
                parts.append(arrow_down(LX + 40, ly - 46, ly))
                if n['gap']:
                    parts.append(gap_label(LX + 52, ly - 19, n['gap']))
            elif n['gap']:
                parts.append(gap_label(mid, ly + 44, n['gap'], '#d9480f', 'middle'))
            svg, h = box(LX, ly, LW, n, LC)
            parts.append(svg)
            ly += h + 46
        bottom = max(bottom, ly - 46)
    H = bottom + 14
    return ('<svg class="sc" width="%d" height="%d" viewBox="0 0 %d %d" xmlns="http://www.w3.org/2000/svg" font-family="Segoe UI, Arial, sans-serif">%s</svg>'
            % (W, H, W, H, ''.join(parts)))


